args <- commandArgs(FALSE)
script <- sub('^--file=', '', args[grepl('^--file=', args)][1])
setwd(dirname(dirname(normalizePath(script))))
r <- read.csv('0923_reproduction_assets/results.csv')
cols <- c(CPC='#CB593C', 'E-OBS'='#187B84', Berkeley='#6554A4')
pdf('0923_reproduction_assets/series.pdf',width=8,height=4.2,family='Helvetica',pointsize=12)
par(mar=c(4.6,4,1,1),las=1,bty='l')
plot(NA,xlim=c(1895,2027),ylim=c(22,34),xlab='Year',ylab='Annual Tx3x (degrees C)')
abline(h=seq(22,34,2),col='#E6E8EB')
for(n in names(cols)){d<-read.csv(paste0('0923_reproduction_assets/',n,'_extremes.csv'));d<-d[d$season=='Annual' & d$used_in_fit,];lines(d$year,d$X,col=cols[n],lwd=1.2)}
legend('topleft',legend=names(cols),col=cols,lty=1,lwd=2,bty='n',horiz=TRUE)
dev.off()
pdf('0923_reproduction_assets/intensity.pdf',width=9,height=5,family='Helvetica',pointsize=12)
par(mar=c(4.6,9,1,1),las=1,bty='n')
d<-r[r$reference=='2003-like',];d<-d[order(d$index,decreasing=TRUE),]
y<-rev(seq_len(nrow(d)))
plot(NA,xlim=c(0,3.4),ylim=c(.5,10.5),yaxt='n',xlab='Intensity change vs 2003-like climate (degrees C)',ylab='')
abline(v=seq(0,3,.5),col='#E6E8EB'); axis(2,at=y,labels=paste(d$dataset,d$index,d$season),tick=FALSE,cex.axis=.9)
segments(d$intensity_low,y,d$intensity_high,y,col=cols[d$dataset],lwd=2.5)
points(d$intensity_change,y,pch=19,col=cols[d$dataset],cex=1.2)
text(d$intensity_high+.08,y,sprintf('%.2f',d$intensity_change),adj=0,cex=.8)
dev.off()
